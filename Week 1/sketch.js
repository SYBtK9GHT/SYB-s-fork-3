let last_time = 0;
let light = 0;

function draw() {
  
  //stoplight`

  const original  = [
    color(255,0,0),
    color(0,255,0),
    color(255,125,0)
  ]
  let light_colors = []
  for (let i = 0; i < original.length; i++){
    light_colors.push(color(0,0,0));
  }
  push();
  translate(350, 25);

  noStroke();
  fill(125);
  rect(0,0,80,240);
  rect(20,240,40,100);

  if (light == 3){
    light = 0;
  }

  for (let i = 0; i < light_colors.length; i++){
      if (i == light){
        light_colors[i] = original[i];
        print(":3")
      }
        
    }

  if (millis() - last_time > 2000){
    
    light++
    last_time = millis()
  }
  
  fill(light_colors[0]);
  circle(40,40,50);
  fill(light_colors[1]);
  circle(40,200,50);
  
  fill(light_colors[2]);
  circle(40,120,50);

  pop();
}