function draw_car(colors, pos, model) {
  const car_colors = [
    color(255, 0, 0),
    color(255, 255, 0),
    color(0, 255, 0),
    color(125, 0, 255),
    color(0, 0, 255),
    color(255),
    color(25),
    color(155),
    color(255,155,0),
    color(0,255,155)
  ];
  
  fill(65)
  rect(pos-135,15,50,10)
  circle(pos-140,20,15)
  fill(car_colors[colors]);
  stroke(car_colors[colors]);
  strokeWeight(1);
  rect(pos - 125, -10, 125, 40);
  rect(pos - 100, -40, 60, 40);

  if (model == 1 || model == 3) {
    triangle(
      pos-125, 30,
      pos-140,-10,
      pos-125,-10);
  }

  if (model == 2 || model == 3){
    triangle(
      pos-40, -40,
      pos-40, -10,
      pos, -10);
  }

  fill (100,155,255)
  rect(pos-90,-30,40,20,5)

  noStroke();
  fill(50);
  circle(pos - 100, 30, 30);
  circle(pos - 25, 30, 30);
}





